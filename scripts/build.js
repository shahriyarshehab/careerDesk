function createBundle(files, kind) {
  const sections = files.map((relativePath) => {
    const absolutePath = path.join(ROOT_DIR, relativePath);
    if (!fs.existsSync(absolutePath)) {
      throw new Error(`Missing ${kind} source file: ${relativePath}`);
    }

    const source = fs.readFileSync(absolutePath, 'utf8')
      .replace(/\r\n?/g, '\n')
      .replace(/[ \t]+$/gm, '')
      .trimEnd();
    return `/* Source: ${relativePath} */\n${source}`;
  });

  const bundle = [
    `/* CareerDesk ${kind} bundle. Generated by npm run build; edit source files, not this file. */`,
    ...sections
  ].join('\n\n') + '\n';

  return bundle;
}

function build() {
  const cssBundle = createBundle(CSS_FILES, 'CSS');
  const jsBundle = createBundle(JS_FILES, 'JavaScript');

  // Fail before writing deployable output if concatenation breaks script syntax.
  new vm.Script(jsBundle, { filename: 'assets/dist/careerdesk.js' });

  fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  const cssPath = path.join(OUTPUT_DIR, 'careerdesk.css');
  const jsPath = path.join(OUTPUT_DIR, 'careerdesk.js');
  fs.writeFileSync(cssPath, cssBundle);
  fs.writeFileSync(jsPath, jsBundle);

  console.log(`Built ${path.relative(ROOT_DIR, cssPath)} from ${CSS_FILES.length} stylesheets.`);
  console.log(`Built ${path.relative(ROOT_DIR, jsPath)} from ${JS_FILES.length} scripts.`);
}

if (require.main === module) {
  build();
}

module.exports = { CSS_FILES, JS_FILES, build };
